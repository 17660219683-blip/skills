/**
 * Extract fresh Douyin cookies from Edge browser using Playwright.
 * Saves cookies in Netscape format for yt-dlp consumption.
 *
 * Usage: node extract_cookies.js [output_path]
 *   output_path defaults to ./_cookies_auto.txt if not specified.
 */

const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");

const DOUYIN_URL = "https://www.douyin.com";
const OUTPUT_DEFAULT = path.join(__dirname, "_cookies_auto.txt");

async function extractCookies(outputPath) {
    console.error("[Cookie] Launching Edge (visible) ...");
    const browser = await chromium.launch({ channel: "msedge", headless: false });

    try {
        const context = await browser.newContext();
        const page = await context.newPage();

        console.error("[Cookie] Navigating to douyin.com ...");
        await page.goto(DOUYIN_URL, { waitUntil: "commit", timeout: 30000 }).catch(() => {});

        await page.waitForTimeout(8000);

        const cookies = await context.cookies();
        console.error("[Cookie] Got " + cookies.length + " cookies");

        let lines = ["# Netscape HTTP Cookie File", "# Auto-generated by Codex", ""];
        for (const c of cookies) {
            const domain = c.domain.startsWith(".") ? c.domain : "." + c.domain;
            const flag = domain.startsWith(".") ? "TRUE" : "FALSE";
            const cp = c.path || "/";
            const sec = c.secure ? "TRUE" : "FALSE";
            const exp = c.expires > 0 ? Math.floor(c.expires) : 0;
            lines.push(domain + "\t" + flag + "\t" + cp + "\t" + sec + "\t" + exp + "\t" + c.name + "\t" + c.value);
        }

        fs.writeFileSync(outputPath, lines.join("\n"), "utf-8");
        console.error("[Cookie] Saved: " + outputPath + " (" + lines.join("\n").length + " bytes)");
    } finally {
        await browser.close();
        console.error("[Cookie] Browser closed.");
    }
}

async function main() {
    const outputPath = process.argv[2] || OUTPUT_DEFAULT;
    await extractCookies(outputPath);
    console.log(outputPath);
}

main().catch((e) => {
    console.error("[Cookie] Extraction failed: " + e.message);
    process.exit(1);
});
